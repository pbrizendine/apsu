-- Apply after quantities-doors.sql. Transactional and safe to rerun.
begin;
create table if not exists public.player_rate_limits (
 player_id uuid not null references auth.users(id) on delete cascade,
 world_id text not null references public.worlds(id) on delete cascade,
 scope text not null, sent_at timestamptz[] not null default '{}',
 primary key(player_id,world_id,scope)
);
alter table public.player_rate_limits enable row level security;
revoke all on public.player_rate_limits from public,anon,authenticated;

-- A locked row serializes requests across tabs, characters, and RPC endpoints.
create or replace function public.take_rate_slot(p_world text,p_scope text,p_gap interval,p_limit int)
returns void language plpgsql security definer set search_path='' as $$
declare stamps timestamptz[]; latest timestamptz; now_at timestamptz := clock_timestamp();
begin
 if auth.uid() is null then raise exception 'Sign in required'; end if;
 insert into public.player_rate_limits(player_id,world_id,scope) values(auth.uid(),p_world,p_scope) on conflict do nothing;
 select sent_at into stamps from public.player_rate_limits where player_id=auth.uid() and world_id=p_world and scope=p_scope for update;
 -- Sample after acquiring the row lock, so concurrent requests cannot use stale time.
 now_at := clock_timestamp();
 select coalesce(array_agg(t order by t),'{}'), max(t) into stamps,latest from unnest(stamps) t where t>now_at-interval '1 minute';
 if latest is not null and latest>now_at-p_gap then raise exception 'Please slow down. Wait % second(s) before trying again.', greatest(1,ceil(extract(epoch from latest+p_gap-now_at))); end if;
 if cardinality(stamps)>=p_limit then raise exception 'Too many messages or commands. Please wait a minute.'; end if;
 update public.player_rate_limits set sent_at=array_append(stamps,now_at) where player_id=auth.uid() and world_id=p_world and scope=p_scope;
end $$;
revoke all on function public.take_rate_slot(text,text,interval,int) from public,anon,authenticated;

create or replace function public.chat_rate_guard() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if tg_table_name='room_messages' then
  -- A whisper's public notice is generated by the server, not a second player send.
  if new.message_type='whisper_notice' then return new; end if;
  if exists(select 1 from public.room_messages where id=new.id) then return new; end if;
  perform public.take_rate_slot(new.world_id,'chat',interval '1 second',20);
 elsif tg_table_name='staff_messages' then
  if exists(select 1 from public.staff_messages where id=new.id) then return new; end if;
  perform public.take_rate_slot(new.world_id,'chat',interval '1 second',20);
 elsif tg_table_name='world_notices' then
  if new.target is not null or exists(select 1 from public.world_notices where id=new.id) then return new; end if;
  perform public.take_rate_slot(new.world_id,'announcement',interval '10 seconds',6);
 end if;
 return new;
end $$;
revoke all on function public.chat_rate_guard() from public,anon,authenticated;
drop trigger if exists chat_rate_guard on public.room_messages;
create trigger chat_rate_guard before insert on public.room_messages for each row execute function public.chat_rate_guard();
drop trigger if exists chat_rate_guard on public.staff_messages;
create trigger chat_rate_guard before insert on public.staff_messages for each row execute function public.chat_rate_guard();
drop trigger if exists chat_rate_guard on public.world_notices;
create trigger chat_rate_guard before insert on public.world_notices for each row execute function public.chat_rate_guard();

create or replace function public.world_online_players(p_world text)
returns table(player_id uuid,username text,character_names text[])
language plpgsql stable security definer set search_path='' as $$
begin
 if auth.uid() is null or public.world_blocked(p_world,auth.uid(),'ban') or not (
  exists(select 1 from public.characters owned where owned.player_id=auth.uid() and owned.world_id=p_world)
  or public.staff_rank(p_world)>0
 ) then raise exception 'Enter this world to view its online players';end if;
 return query select u.id,coalesce(nullif(btrim(u.raw_user_meta_data->>'username'),''),'Player'),array_agg(distinct c.name order by c.name)
 from public.chat_visits v join public.characters c on c.id=v.character_id and c.world_id=v.world_id and c.room_id=v.room_id
 join auth.users u on u.id=v.player_id
 where v.world_id=p_world and v.active and v.seen_at>now()-interval '60 seconds'
 group by u.id order by lower(coalesce(u.raw_user_meta_data->>'username','Player')),u.id;
end $$;
revoke all on function public.world_online_players(text) from public,anon;
grant execute on function public.world_online_players(text) to authenticated;

-- Retry-safe registration prevents duplicate visits after an uncertain response.
create or replace function public.enter_chat(p_visit uuid,p_character uuid,p_room text) returns uuid language plpgsql security definer set search_path='' as $$
declare c public.characters; existing public.chat_visits;
begin
 select * into c from public.characters where id=p_character and player_id=auth.uid() for update;
 if not found or p_visit is null or p_room is null or c.room_id<>p_room then raise exception 'Invalid chat visit';end if;
 select * into existing from public.chat_visits where id=p_visit;
 if found then
  if existing.player_id=auth.uid() and existing.character_id=c.id and existing.room_id=p_room and existing.active and existing.seen_at>clock_timestamp()-interval '60 seconds' then return p_visit;end if;
  raise exception 'Chat visit expired';
 end if;
 insert into public.chat_visits(id,player_id,character_id,world_id,room_id) values(p_visit,auth.uid(),c.id,c.world_id,p_room);
 return p_visit;
end $$;

create or replace function public.touch_chat(p_visit uuid,p_leave boolean default false) returns boolean language plpgsql security definer set search_path='' as $$
declare v public.chat_visits;
begin
 update public.chat_visits set seen_at=clock_timestamp(),active=not p_leave
 where id=p_visit and player_id=auth.uid() and active and seen_at>clock_timestamp()-interval '60 seconds'
 returning * into v;
 if not found then return false;end if;
 if p_leave and not exists(select 1 from public.chat_visits where character_id=v.character_id and active and seen_at>clock_timestamp()-interval '60 seconds') then
  update public.lock_use set token=null,player_id=null,character_id=null,expires_at='-infinity'
  where player_id=auth.uid() and character_id=v.character_id and world_id=v.world_id;
 end if;
 return true;
end $$;
commit;
